import type { CatalogModel, ModelCatalog } from '../src/types.ts'
import { createHash, randomUUID } from 'node:crypto'
import { readFile, rename, rm, writeFile } from 'node:fs/promises'
import process from 'node:process'
import { pathToFileURL } from 'node:url'
import { catalogMetadata, modelCatalog } from '../src/catalog.generated.ts'
import { record, text } from '../src/validation.ts'

export const catalogURL = 'https://models.dev/api.json'
export const sources = ['opencode-go', 'commandcode'] as const
const target = new URL('../src/catalog.generated.ts', import.meta.url)
const digest = (value: unknown): string => createHash('sha256').update(JSON.stringify(value)).digest('hex')

export function normalizeCatalog(input: unknown): Pick<ModelCatalog, typeof sources[number]> {
  const root = record(input, 'models.dev catalog')
  return Object.fromEntries(sources.map((source) => {
    const provider = record(root[source], `provider ${source}`)
    const models = Object.entries(record(provider.models, `${source}.models`)).flatMap(([key, raw]): CatalogModel[] => {
      const model = record(raw, `${source}/${key}`)
      if (model.tool_call !== true || model.status === 'deprecated')
        return []
      const modalities = record(model.modalities ?? {}, 'model modalities')
      if (!Array.isArray(modalities.input) || !modalities.input.includes('text') || !Array.isArray(modalities.output) || !modalities.output.includes('text'))
        return []
      const limit = record(model.limit, 'model limits')
      const contextWindow = limit.context
      const maxTokens = limit.output
      if (typeof contextWindow !== 'number' || !Number.isSafeInteger(contextWindow) || contextWindow <= 0 || typeof maxTokens !== 'number' || !Number.isSafeInteger(maxTokens) || maxTokens <= 0)
        throw new Error(`Invalid model limits: ${source}/${key}`)
      const options = model.reasoning_options ?? []
      if (!Array.isArray(options))
        throw new TypeError('Invalid reasoning options')
      const efforts = options.flatMap((raw) => {
        const option = record(raw, 'reasoning option')
        if (option.type !== 'effort')
          return []
        const values = option.values ?? []
        if (!Array.isArray(values))
          throw new TypeError('Invalid reasoning efforts')
        return values.map((value) => {
          if (typeof value !== 'string' || !/^[a-z]+$/u.test(value))
            throw new Error('Invalid reasoning effort')
          return value
        })
      })
      const interleaved = model.interleaved == null || typeof model.interleaved === 'boolean'
        ? undefined
        : record(model.interleaved, 'interleaved reasoning')
      return [
        {
          id: text(model.id, 'model id', 512),
          name: text(model.name, 'model name', 512),
          contextWindow,
          maxTokens,
          input: modalities.input.filter((value): value is 'text' | 'image' => value === 'text' || value === 'image'),
          reasoning: model.reasoning === true,
          reasoningEfforts: [
            ...new Set(efforts),
          ],
          ...(interleaved?.field
            ? {
                reasoningField: text(interleaved.field, 'reasoning field'),
              }
            : {}),
        },
      ]
    }).sort((a, b) => a.id.localeCompare(b.id, 'en'))
    if (!models.length || new Set(models.map(model => model.id)).size !== models.length)
      throw new Error(`Empty or duplicate models: ${source}`)
    return [source, models]
  })) as Pick<ModelCatalog, typeof sources[number]>
}

export async function main(args = process.argv.slice(2)): Promise<void> {
  if (args.includes('--check')) {
    if (catalogMetadata.source !== catalogURL || digest(modelCatalog) !== catalogMetadata.sha256 || modelCatalog.openai.length || !sources.every(source => modelCatalog[source].length))
      throw new Error('Invalid model snapshot; run pnpm models:update')
    console.log('Using checked-in models.dev snapshot (pnpm models:update to refresh)')
    return
  }
  const response = await fetch(catalogURL, {
    signal: AbortSignal.timeout(30_000),
    redirect: 'error',
  })
  if (!response.ok)
    throw new Error(`models.dev returned HTTP ${response.status}; previous snapshot was not changed`)
  const catalog: ModelCatalog = {
    openai: [],
    ...normalizeCatalog(await response.json()),
  }
  const metadata = {
    source: catalogURL,
    generatedAt: new Date().toISOString(),
    sha256: digest(catalog),
  }
  const previous = await readFile(target, 'utf8')
  const source = `// Generated by pnpm models:update. Do not edit.\nimport type { ModelCatalog } from './types.js'\n\nexport const catalogMetadata = ${JSON.stringify(metadata)} as const\n\nexport const modelCatalog: ModelCatalog = ${JSON.stringify(catalog, null, 2)}\n`
  // Atomic replacement requires a staging file on the snapshot's own volume.
  const staging = new URL(`${target.href}.${randomUUID()}.tmp`)
  try {
    await writeFile(staging, source, { flag: 'wx' })
    if (await readFile(target, 'utf8') !== previous)
      throw new Error('Snapshot changed during update; retry')
    await rename(staging, target)
  }
  finally {
    await rm(staging, { force: true })
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error instanceof Error
      ? error.message
      : 'Model update failed')
    process.exitCode = 1
  })
}
